def denormalise(index, value):
    """Map a stored 0..1 parameter to the value Serum displays."""
    _, lo, hi, _, _ = PARAMS[index]
    return lo + (hi - lo) * value


def normalised_default(index):
    """The factory default of parameter `index`, in stored 0..1 form."""
    _, lo, hi, _, default = PARAMS[index]
    if hi == lo:
        return 0.5
    return (default - lo) / (hi - lo)
